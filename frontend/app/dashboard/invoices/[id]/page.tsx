"use client";

import Link from "next/link";
import { useParams } from "next/navigation";
import { useEffect, useState } from "react";
import ProtectedRoute from "../../../components/ProtectedRoute";
import { addInvoiceNote, getInvoiceReview, InvoiceReview, updateInvoiceStatus } from "../../../lib/invoices";

const statusStyles: Record<InvoiceReview["status"], string> = {
  ready_for_review: "bg-slate-100 text-slate-700",
  needs_review: "bg-amber-100 text-amber-700",
  approved: "bg-emerald-100 text-emerald-700",
  rejected: "bg-rose-100 text-rose-700",
};

const riskStyles: Record<InvoiceReview["riskLevel"], string> = {
  low: "bg-emerald-100 text-emerald-700",
  medium: "bg-amber-100 text-amber-700",
  high: "bg-rose-100 text-rose-700",
};

export default function InvoiceDetailPage() {
  const params = useParams<{ id: string }>();
  const [invoice, setInvoice] = useState<InvoiceReview | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [isUpdating, setIsUpdating] = useState(false);
  const [noteText, setNoteText] = useState("");
  const [isSavingNote, setIsSavingNote] = useState(false);
  const [noteError, setNoteError] = useState("");

  useEffect(() => {
    let isCurrent = true;

    async function loadInvoice() {
      setLoading(true);
      setError("");

      try {
        const { invoice: loadedInvoice } = await getInvoiceReview(params.id);
        if (isCurrent) setInvoice(loadedInvoice);
      } catch (requestError) {
        if (isCurrent) {
          setError(requestError instanceof Error ? requestError.message : "Could not load the invoice.");
        }
      } finally {
        if (isCurrent) setLoading(false);
      }
    }

    if (params.id) loadInvoice();
    return () => {
      isCurrent = false;
    };
  }, [params.id]);

  const handleStatusUpdate = async (status: InvoiceReview["status"]) => {
    if (!invoice) return;

    setIsUpdating(true);
    try {
      const { invoice: updatedInvoice } = await updateInvoiceStatus(invoice.id, status);
      setInvoice(updatedInvoice);
    } catch (requestError) {
      setError(requestError instanceof Error ? requestError.message : "Could not update the invoice status.");
    } finally {
      setIsUpdating(false);
    }
  };

  const handleAddNote = async (event: React.FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    if (!invoice || !noteText.trim()) return;

    setIsSavingNote(true);
    setNoteError("");
    try {
      const { invoice: updatedInvoice } = await addInvoiceNote(invoice.id, noteText);
      setInvoice(updatedInvoice);
      setNoteText("");
    } catch (requestError) {
      setNoteError(requestError instanceof Error ? requestError.message : "Could not save the note.");
    } finally {
      setIsSavingNote(false);
    }
  };

  const handleDownloadReport = () => {
    if (!invoice) return;

    const currency = new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" });
    const lines = [
      "INVOICE AUDIT SUMMARY",
      `Invoice: ${invoice.invoiceNumber || `#${invoice.id}`}`,
      `Vendor: ${invoice.vendor}`,
      `Amount: ${currency.format(Number(invoice.amount))}`,
      `Status: ${invoice.status.replaceAll("_", " ")}`,
      `Risk: ${invoice.riskLevel} (${invoice.riskScore}/100)`,
      `Document: ${invoice.documentName || "Not provided"}`,
      `Submitted: ${new Date(invoice.createdAt).toLocaleString()}`,
      "",
      "FINDINGS",
      ...(invoice.findings.length
        ? invoice.findings.map((finding) => `- [${finding.severity.toUpperCase()}] ${finding.code}: ${finding.message}`)
        : ["- No findings recorded."]),
      "",
      "STATUS HISTORY",
      ...(invoice.statusHistory?.length
        ? invoice.statusHistory.map((entry) => `- ${entry.status.replaceAll("_", " ")} at ${new Date(entry.changedAt).toLocaleString()}`)
        : ["- No status history recorded."]),
      "",
      "REVIEW NOTES",
      ...(invoice.reviewNotes?.length
        ? invoice.reviewNotes.map((entry) => `- ${new Date(entry.createdAt).toLocaleString()} | ${entry.author} (${entry.email}): ${entry.note}`)
        : ["- No reviewer notes recorded."]),
      "",
      "Generated by Invoice Auditor. Risk checks are rule-based and are not accounting advice.",
    ];
    const report = new Blob([lines.join("\n")], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(report);
    const link = document.createElement("a");
    link.href = url;
    link.download = `invoice-audit-${invoice.invoiceNumber || invoice.id}.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <ProtectedRoute>
      <main className="min-h-screen bg-slate-100 px-6 py-8 md:px-10">
        <div className="mx-auto max-w-5xl">
          <div className="mb-6 flex items-center justify-between">
            <Link href="/dashboard" className="text-sm font-medium text-indigo-600 hover:text-indigo-500">
              Back to dashboard
            </Link>
          </div>

          {loading ? (
            <div className="rounded-2xl border border-slate-200 bg-white p-8 text-slate-500 shadow-sm">
              Loading invoice details...
            </div>
          ) : error && !invoice ? (
            <div className="rounded-2xl border border-rose-200 bg-rose-50 p-6 text-rose-700 shadow-sm">
              {error}
            </div>
          ) : invoice ? (
            <div className="space-y-6">
              {error && (
                <p role="alert" className="rounded-xl border border-rose-200 bg-rose-50 p-4 text-sm text-rose-700">
                  {error}
                </p>
              )}
              <section className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm md:p-8">
                <div className="flex flex-col gap-5 md:flex-row md:items-start md:justify-between">
                  <div>
                    <p className="text-sm font-medium uppercase tracking-[0.2em] text-slate-500">Invoice detail</p>
                    <h1 className="mt-2 text-3xl font-bold text-slate-900">
                      {invoice.invoiceNumber || `Invoice #${invoice.id}`}
                    </h1>
                    <p className="mt-2 text-sm text-slate-600">{invoice.vendor}</p>
                  </div>

                  <div className="flex flex-col items-start gap-3 md:items-end">
                    <button
                      type="button"
                      onClick={handleDownloadReport}
                      className="rounded-lg border border-slate-300 bg-white px-3 py-2 text-sm font-semibold text-slate-700 transition hover:bg-slate-50 focus-visible:outline-none focus-visible:ring-4 focus-visible:ring-indigo-100"
                    >
                      Download audit summary
                    </button>
                    <span className={`rounded-full px-3 py-1 text-xs font-semibold ${riskStyles[invoice.riskLevel]}`}>
                      {invoice.riskLevel} risk
                    </span>
                    <span className={`rounded-full px-3 py-1 text-xs font-semibold ${statusStyles[invoice.status]}`}>
                      {invoice.status.replaceAll("_", " ")}
                    </span>
                  </div>
                </div>

                <div className="mt-6 grid gap-4 md:grid-cols-2 xl:grid-cols-4">
                  <div className="rounded-xl bg-slate-50 p-4">
                    <p className="text-xs font-semibold uppercase tracking-[0.15em] text-slate-500">Amount</p>
                    <p className="mt-2 text-2xl font-bold text-slate-900">
                      ${Number(invoice.amount).toLocaleString("en-US", { minimumFractionDigits: 2 })}
                    </p>
                  </div>
                  <div className="rounded-xl bg-slate-50 p-4">
                    <p className="text-xs font-semibold uppercase tracking-[0.15em] text-slate-500">Risk score</p>
                    <p className="mt-2 text-2xl font-bold text-slate-900">{invoice.riskScore}/100</p>
                  </div>
                  <div className="rounded-xl bg-slate-50 p-4">
                    <p className="text-xs font-semibold uppercase tracking-[0.15em] text-slate-500">Document</p>
                    <p className="mt-2 text-sm font-medium text-slate-800">{invoice.documentName || "No document name"}</p>
                  </div>
                  <div className="rounded-xl bg-slate-50 p-4">
                    <p className="text-xs font-semibold uppercase tracking-[0.15em] text-slate-500">Submitted</p>
                    <p className="mt-2 text-sm font-medium text-slate-800">{new Date(invoice.createdAt).toLocaleString()}</p>
                  </div>
                </div>
              </section>

              <section className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm md:p-8">
                <p className="text-sm font-medium uppercase tracking-[0.2em] text-slate-500">Reviewer notes</p>
                <form onSubmit={handleAddNote} className="mt-4 space-y-3">
                  <label htmlFor="review-note" className="block text-sm font-medium text-slate-700">
                    Add a note to this invoice
                  </label>
                  <textarea
                    id="review-note"
                    value={noteText}
                    onChange={(event) => setNoteText(event.target.value)}
                    maxLength={2000}
                    rows={3}
                    placeholder="Record context, follow-up, or the reason for your decision..."
                    className="w-full resize-y rounded-xl border border-slate-300 bg-white px-3 py-3 text-sm text-slate-900 placeholder:text-slate-400 outline-none transition focus:border-indigo-500 focus:ring-4 focus:ring-indigo-100"
                  />
                  <div className="flex flex-wrap items-center justify-between gap-3">
                    <span className="text-xs text-slate-500">{noteText.length}/2,000 characters</span>
                    <button
                      type="submit"
                      disabled={isSavingNote || !noteText.trim()}
                      className="rounded-lg bg-slate-900 px-4 py-2 text-sm font-semibold text-white transition hover:bg-slate-700 disabled:cursor-not-allowed disabled:opacity-50"
                    >
                      {isSavingNote ? "Saving..." : "Add note"}
                    </button>
                  </div>
                  {noteError && <p role="alert" className="text-sm text-rose-700">{noteError}</p>}
                </form>
                <div className="mt-6 space-y-3">
                  {invoice.reviewNotes?.length ? (
                    [...invoice.reviewNotes].reverse().map((entry, index) => (
                      <article key={`${entry.createdAt}-${index}`} className="rounded-xl border border-slate-200 bg-slate-50 p-4">
                        <p className="whitespace-pre-wrap text-sm text-slate-800">{entry.note}</p>
                        <p className="mt-3 text-xs text-slate-500">
                          {entry.author} · {new Date(entry.createdAt).toLocaleString()}
                        </p>
                      </article>
                    ))
                  ) : (
                    <p className="text-sm text-slate-500">No notes have been added yet.</p>
                  )}
                </div>
              </section>

              <section className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm md:p-8">
                <div className="flex flex-col gap-4 md:flex-row md:items-center md:justify-between">
                  <div>
                    <p className="text-sm font-medium uppercase tracking-[0.2em] text-slate-500">Review actions</p>
                    <h2 className="mt-2 text-xl font-semibold text-slate-900">Decision workflow</h2>
                  </div>

                  <div className="flex flex-wrap gap-3">
                    <button
                      type="button"
                      disabled={isUpdating}
                      onClick={() => handleStatusUpdate("approved")}
                      className="rounded-xl bg-emerald-600 px-4 py-2 text-sm font-semibold text-white transition hover:bg-emerald-500 disabled:opacity-60"
                    >
                      Approve
                    </button>
                    <button
                      type="button"
                      disabled={isUpdating}
                      onClick={() => handleStatusUpdate("rejected")}
                      className="rounded-xl border border-rose-200 bg-rose-50 px-4 py-2 text-sm font-semibold text-rose-700 transition hover:bg-rose-100 disabled:opacity-60"
                    >
                      Reject
                    </button>
                    <button
                      type="button"
                      disabled={isUpdating}
                      onClick={() => handleStatusUpdate("needs_review")}
                      className="rounded-xl border border-amber-200 bg-amber-50 px-4 py-2 text-sm font-semibold text-amber-700 transition hover:bg-amber-100 disabled:opacity-60"
                    >
                      Escalate
                    </button>
                  </div>
                </div>
              </section>

              <section className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm md:p-8">
                <p className="text-sm font-medium uppercase tracking-[0.2em] text-slate-500">Vendor benchmark</p>
                <div className="mt-4 rounded-xl bg-slate-50 p-4">
                  {invoice.vendorHistory && invoice.vendorHistory.length > 0 ? (
                    <div className="space-y-2 text-sm text-slate-700">
                      <p><span className="font-semibold text-slate-900">Recent count:</span> {invoice.vendorHistory[0].count} invoices</p>
                      <p><span className="font-semibold text-slate-900">Average amount:</span> ${Number(invoice.vendorHistory[0].averageAmount).toLocaleString("en-US", { minimumFractionDigits: 2 })}</p>
                      <p><span className="font-semibold text-slate-900">Highest amount:</span> ${Number(invoice.vendorHistory[0].maxAmount).toLocaleString("en-US", { minimumFractionDigits: 2 })}</p>
                    </div>
                  ) : (
                    <p className="text-sm text-slate-600">Not enough vendor history yet for benchmarking.</p>
                  )}
                </div>
              </section>

              <section className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm md:p-8">
                <p className="text-sm font-medium uppercase tracking-[0.2em] text-slate-500">Status history</p>
                <div className="mt-5 space-y-3">
                  {invoice.statusHistory && invoice.statusHistory.length > 0 ? (
                    invoice.statusHistory.map((entry, index) => (
                      <div key={`${entry.status}-${index}`} className="flex items-center justify-between rounded-xl border border-slate-200 bg-slate-50 px-4 py-3 text-sm">
                        <span className="font-medium text-slate-800">{entry.status.replaceAll("_", " ")}</span>
                        <span className="text-slate-500">{new Date(entry.changedAt).toLocaleString()}</span>
                      </div>
                    ))
                  ) : (
                    <p className="text-sm text-slate-600">No status updates for this invoice yet.</p>
                  )}
                </div>
              </section>

              <section className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm md:p-8">
                <p className="text-sm font-medium uppercase tracking-[0.2em] text-slate-500">Findings</p>
                <div className="mt-5 space-y-3">
                  {invoice.findings.map((finding) => (
                    <div
                      key={finding.code}
                      className={`rounded-xl border p-4 ${
                        finding.severity === "high"
                          ? "border-rose-200 bg-rose-50"
                          : finding.severity === "medium"
                            ? "border-amber-200 bg-amber-50"
                            : "border-emerald-200 bg-emerald-50"
                      }`}
                    >
                      <div className="flex items-center justify-between gap-3">
                        <p className="text-sm font-semibold text-slate-900">{finding.code.replaceAll("_", " ")}</p>
                        <span className="rounded-full bg-white px-2 py-1 text-[10px] font-semibold uppercase tracking-wide text-slate-700">
                          {finding.severity}
                        </span>
                      </div>
                      <p className="mt-2 text-sm text-slate-700">{finding.message}</p>
                    </div>
                  ))}
                </div>
              </section>
            </div>
          ) : null}
        </div>
      </main>
    </ProtectedRoute>
  );
}
